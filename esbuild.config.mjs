import esbuild from "esbuild";
import { copyFileSync, mkdirSync, readFileSync } from "fs";
import process from "process";
import { pathToFileURL } from "url";

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const mode = process.argv[2] ?? "dev";
const version = JSON.parse(readFileSync("package.json", "utf8")).version;

const pluginOptions = {
  banner: { js: banner },
  entryPoints: ["src/main.ts"],
  bundle: true,
  external: [
    "obsidian",
    "electron",
    "@codemirror/autocomplete",
    "@codemirror/collab",
    "@codemirror/commands",
    "@codemirror/language",
    "@codemirror/lint",
    "@codemirror/search",
    "@codemirror/state",
    "@codemirror/view",
    "@lezer/common",
    "@lezer/highlight",
    "@lezer/lr",
  ],
  format: "cjs",
  target: "es2018",
  logLevel: "info",
  treeShaking: true,
  outfile: "main.js",
};

/** Standalone browser builds: an IIFE that auto-renders and a passive ES module. */
export async function buildWeb() {
  mkdirSync("dist", { recursive: true });
  const common = {
    entryPoints: ["src/web.ts"],
    bundle: true,
    minify: true,
    target: "es2018",
    logLevel: "info",
    treeShaking: true,
    sourcemap: "linked",
  };
  await esbuild.build({
    ...common,
    format: "iife",
    globalName: "CoolChordSheets",
    define: { __AUTO__: "true", __VERSION__: JSON.stringify(version) },
    outfile: "dist/coolchordsheets.js",
  });
  await esbuild.build({
    ...common,
    format: "esm",
    define: { __AUTO__: "false", __VERSION__: JSON.stringify(version) },
    outfile: "dist/coolchordsheets.esm.js",
  });
  copyFileSync("styles.css", "dist/coolchordsheets.css");
}

// Only act as a CLI when run directly; scripts and tests import buildWeb from this file.
const isEntry = process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url;
if (isEntry) {
  if (mode === "web") {
    await buildWeb();
  } else if (mode === "production") {
    await esbuild.build({ ...pluginOptions, sourcemap: false });
  } else {
    const context = await esbuild.context({ ...pluginOptions, sourcemap: "inline" });
    await context.watch();
  }
}
